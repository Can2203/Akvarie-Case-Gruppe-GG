function hideUnhide(id) {
    const p1 = document.getElementById(id);

    if (p1.style.display == "none") {
        p1.style.display = "block";
        p1.style.display = "flex";
    } else {
        p1.style.display = "none";
        p1.style.color = "transparent";
    }

}

